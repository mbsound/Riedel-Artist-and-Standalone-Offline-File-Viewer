#!/usr/bin/env python3
"""
Artist Matrix .Art File Extractor
=================================
Parses Artist digital matrix intercom configuration files (.Art)
generated by Director software, extracting:
  - System metadata (Director software release, Matrix Node & Frame names)
  - Multi-Node network topology (Fiber Ring nodes, Control IPs, Subnets, Gateways)
  - Hardware configuration (Chassis Cards & Slots: AES67, MADI, Dante, AIO, etc.)
  - Per-card network settings (Primary/Secondary streaming IPs & Gateways)
  - Digital IP Trunk Lines (VoIP & direct matrix trunks with remote IPs)
  - Wireless endpoints & Multicast IP addressing (Bolero beltpacks, roles, streams)
  - Matrix Ports & Endpoints (Mainframe Bay ports, SmartPanels, Radio interfaces)
  - Conferences & Partylines (Long names & OLED display labels)
  - IFB routing & Remote labels (IFB channels, remote controllers, and foldbacks)
  - Logic functions, Flashes, & GPIO signalization definitions
  - Users, roles, and administrative security accounts
  - Professional formatted Excel export (.xlsx) & optional JSON export

Usage:
    python3 art_extractor.py                     # process all *.Art in current dir
    python3 art_extractor.py file.Art            # process specific file
    python3 art_extractor.py -o export.xlsx      # specify output file name
    python3 art_extractor.py file.Art --json     # export JSON as well
"""

