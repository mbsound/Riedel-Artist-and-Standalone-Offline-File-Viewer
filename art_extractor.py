def find_master_port_table(data):
    """Dynamically locates the master endpoint table (count uint32 followed by 8-byte type/ID entries)."""
    for i in range(0, min(len(data)-12, 0x10000)):
        cnt = int.from_bytes(data[i:i+4], "little")
        if 8 <= cnt <= 1024:
            tcs = [int.from_bytes(data[i+4+j*8:i+8+j*8], "little") for j in range(min(cnt, 4))]
            if all((tc >> 8) in (0x04, 0x05) for tc in tcs):
                entries = []
                for j in range(cnt):
                    entry = data[i+4+j*8 : i+4+(j+1)*8]
                    tc = int.from_bytes(entry[:4], "little")
                    oid = int.from_bytes(entry[4:8], "little")
                    entries.append((tc, oid))
                return i, cnt, entries
    return None, 0, []

def clean_val(val):
    if val is None:
        return ""
    s = str(val)
    return ILLEGAL_CHARACTERS_RE.sub("", s)

def fill(hex_c):
    return PatternFill(start_color=hex_c, end_color=hex_c, fill_type="solid")

def bdr(style="thin", color="D9D9D9"):
    s = Side(style=style, color=color)
    return Border(left=s, right=s, top=s, bottom=s)

def auto_width(ws, extra=3, max_w=70):
    for col in ws.columns:
        ltr = get_column_letter(col[0].column)
        w = max((len(str(c.value or "")) for c in col), default=0)
        ws.column_dimensions[ltr].width = min(max(w + extra, 10), max_w)

def title_row(ws, title, subtitle, max_col=7):
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=max_col)
    c = ws.cell(row=1, column=1, value=clean_val(title))
    c.font = Font(name="Calibri", size=14, bold=True, color="FFFFFF")
    c.fill = fill(C["dark_blue"])
    c.alignment = Alignment(horizontal="left", vertical="center", indent=1)
    ws.row_dimensions[1].height = 32

    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=max_col)
    c2 = ws.cell(row=2, column=1, value=clean_val(subtitle))
    c2.font = Font(name="Calibri", size=9, italic=True, color="FFFFFF")
    c2.fill = fill(C["mid_blue"])
    c2.alignment = Alignment(horizontal="left", vertical="center", indent=1)
    ws.row_dimensions[2].height = 18

